/**
 * Deterministic deployment guide shipped inside every source archive. It uses
 * only commands the generated project can be expected to expose through
 * package.json; it does not claim a framework the archive may not contain.
 */
export function buildDeployGuide(): string {
  return [
    "# Deployment Guide",
    "",
    "This archive contains the delivered source and its verification reports.",
    "The exact runtime, framework, and scripts are declared in `package.json`; read",
    "that file before choosing a host.",
    "",
    "## 1. Verify the archive",
    "",
    "```bash",
    "sha256sum -c CHECKSUMS.txt",
    "```",
    "",
    "Every listed file is covered. `CHECKSUMS.txt` does not checksum itself.",
    "",
    "## 2. Install and build locally",
    "",
    "```bash",
    "npm ci",
    "npm run build",
    "```",
    "",
    "Use the package manager lockfile that is present. If the project has no",
    "`package-lock.json`, run `npm install` once and commit the generated lockfile",
    "before deploying.",
    "",
    "## 3. Configure environment",
    "",
    "Create a local `.env` from `.env.example` if one is present. Never commit",
    "`.env` files or provider secrets. The build report and evidence ledger describe",
    "what was verified; they do not contain credentials.",
    "",
    "## 4. Run",
    "",
    "```bash",
    "npm start",
    "```",
    "",
    "If `package.json` does not define `start`, use the framework's documented",
    "production command instead of inventing one.",
    "",
    "## 5. Container deployment",
    "",
    "Build from the repository root with your platform's Node 20+ image. Mount",
    "secrets at runtime, run the production build during the image build, and",
    "expose the port declared by the application. Do not copy `.env` into the",
    "image.",
    "",
    "## 6. Git history",
    "",
    "The Git delivery archive contains `.git` and one commit per accepted Studio",
    "version, using the real version timestamps. Push it to an existing empty",
    "repository:",
    "",
    "```bash",
    "git remote add origin <your-repository-url>",
    "git push -u origin main",
    "```",
    "",
    "A GitHub push from the RevForge delivery page is available only when the",
    "deployment operator enables `ENABLE_GITHUB_PUSH` and configures a token.",
    "",
    "## 7. What was not verified",
    "",
    "Read `PARITY_REPORT.md` before launch. Dimensions marked `not verified` were",
    "not measured. Production infrastructure, third-party credentials, and",
    "provider-side behaviour remain the deployer's responsibility.",
    "",
  ].join("\n");
}
